import streamlit as st
import joblib
import pandas as pd

model = joblib.load('medical_cost_model.pkl')

st.title("Medical Cost Prediction")
st.write("H.M.D.N. Herath (SA25610046) | Linear Regression | R2 = 0.8871 | MAE = $2830")

age = st.slider("Age", 18, 64, 30)
sex = st.radio("Sex", ["male", "female"])
bmi = st.slider("BMI", 15.0, 53.0, 25.0)
children = st.slider("Children", 0, 5, 0)
smoker = st.radio("Smoker", ["yes", "no"])
region = st.selectbox("Region", ["northeast", "northwest", "southeast", "southwest"])

if st.button("Predict Cost"):
    if bmi < 18.5: bmi_cat = 'underweight'
    elif bmi < 25: bmi_cat = 'normal'
    elif bmi < 30: bmi_cat = 'overweight'
    else: bmi_cat = 'obese'

    if age < 30: age_grp = 'young'
    elif age < 50: age_grp = 'middle'
    else: age_grp = 'senior'

    data = pd.DataFrame([{
        'age': age, 'sex': sex, 'bmi': bmi, 'children': children,
        'smoker': smoker, 'region': region,
        'bmi_category': bmi_cat, 'age_group': age_grp,
        'smoker_bmi': bmi if smoker == 'yes' else 0,
        'is_obese': 1 if bmi >= 30 else 0,
        'is_smoker': 1 if smoker == 'yes' else 0
    }])
    pred = model.predict(data)[0]
    st.success(f"Estimated Medical Cost: ${pred:,.2f}")